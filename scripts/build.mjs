import {createHash} from 'node:crypto';
import {readdir, readFile, unlink, writeFile} from 'node:fs/promises';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';

const projectRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const scriptDirectory = join(projectRoot, 'flappy-assets', 'script');
const styleDirectory = join(projectRoot, 'flappy-assets', 'style');
const indexPath = join(projectRoot, 'index.html');

const moduleOrder = ['config.js', 'physics.js', 'storage.js', 'flappy.js', 'app.js'];
const moduleSources = await Promise.all(
    moduleOrder.map((filename) => readFile(join(scriptDirectory, filename), 'utf8'))
);

const bundle = moduleSources
    .map((source, index) => `// ---- ${moduleOrder[index]} ----\n${stripModuleSyntax(source).trim()}\n`)
    .join('\n');
const scriptHash = hash(bundle);
const scriptFilename = `app.${scriptHash}.js`;

const stylesheet = await readFile(join(styleDirectory, 'styles.css'), 'utf8');
const styleHash = hash(stylesheet);
const styleFilename = `styles.${styleHash}.css`;

await removeOldBuilds(scriptDirectory, /^app\.[a-f0-9]{12}\.js$/, scriptFilename);
await removeOldBuilds(styleDirectory, /^styles\.[a-f0-9]{12}\.css$/, styleFilename);

await writeFile(
    join(scriptDirectory, scriptFilename),
    `// Generated by npm run build. Do not edit.\n${bundle}`
);
await writeFile(join(styleDirectory, styleFilename), stylesheet);

const index = await readFile(indexPath, 'utf8');
if (!index.includes('<!-- build:css -->') || !index.includes('<!-- build:js -->')) {
    throw new Error('Build markers are missing from index.html');
}

const nextIndex = index
    .replace(
        /<!-- build:css -->[\s\S]*?<!-- \/build:css -->/,
        `<!-- build:css -->\n  <link rel="stylesheet" href="flappy-assets/style/${styleFilename}">\n  <!-- /build:css -->`
    )
    .replace(
        /<!-- build:js -->[\s\S]*?<!-- \/build:js -->/,
        `<!-- build:js -->\n<script defer src="./flappy-assets/script/${scriptFilename}"></script>\n<!-- /build:js -->`
    );

if (nextIndex !== index) await writeFile(indexPath, nextIndex);
console.log(`Built ${scriptFilename} and ${styleFilename}`);

function stripModuleSyntax(source) {
    return source
        .replace(/^import\s+[\s\S]*?\s+from\s+['"][^'"]+['"];?\s*$/gm, '')
        .replace(/\bexport\s+(?=(?:const|function|class)\b)/g, '');
}

function hash(content) {
    return createHash('sha256').update(content).digest('hex').slice(0, 12);
}

async function removeOldBuilds(directory, pattern, keepFilename) {
    const entries = await readdir(directory);
    await Promise.all(
        entries
            .filter((filename) => pattern.test(filename) && filename !== keepFilename)
            .map((filename) => unlink(join(directory, filename)))
    );
}
